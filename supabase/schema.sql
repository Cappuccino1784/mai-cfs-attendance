create table if not exists public.members (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null,
  emoji text not null default '🌸'
);

create table if not exists public.hangouts (
  id bigint generated by default as identity primary key,
  date date not null unique,
  label text,
  created_at timestamptz not null default now()
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  hangout_id bigint not null references public.hangouts(id) on delete cascade,
  person_name text not null references public.members(name) on update cascade,
  present boolean not null default false,
  unique (hangout_id, person_name)
);

